2 – على المقاول تأمين وتوفير جميع الإمكانات (بما في ذلك العدد والأدوات والآليات... إلخ) والمواد اللازمة لتنفيذ الأعمال بالمستوى المطلوب، ويتحمل المقاول المسؤولية والتكاليف المترتبة على تأمين تلك المتطلبات (بما في ذلك تكاليف الشحن والتخليص والنقل والرفع...إلخ).
