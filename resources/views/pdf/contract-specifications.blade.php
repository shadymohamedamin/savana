            2.5- اسمنت بلاستر داخلي: لجدران الحمامات و المطبخ و الغسيل. الإسمنت المستخدم لجميع أعمال البلاستر تحت منسوب الأرض الطبيعية يجب أن يكون من الإسمنت المقاوم للأملاح (SRC).<br><br>

