4 – على المقاول اتخاذ كافة الاحتياطات لضمان سلامة الأشخاص والمباني المجاورة طيلة مدة التنفيذ وخاصة فيما يتعلق بأعمال السقالات والحماية للعاملين في المناطق العالية المفتوحة، وعلى المقاول وضع لوحات بكافة الإرشادات اللازمة لمتطلبات السلامة
5 – على المقاول إعداد برنامج زمني تفصيلي لتنفيذ الأعمال، واعتماده من الاستشاري قبل البدء بالتنفيذ بطريقة  C.P.M
6 – على المقاول تقديم تقرير شهري مدعم بالصور للإستشاري يوضح فيه سير العمل ومدى تطابقه مع برنامج سير العمل إضافة إلى جداول تبين عدد وتوزيع العمالة والآليات المستخدمة في الموقع، وأية بيانات أخرى يطلبها الاستشاري. 
7 – على المقاول المحافظة على إبقاء الموقع (والأعمال المنفذة) نظيفة من الداخل والخارج طيلة مدة التنفيذ، واتخاذ جميع الترتيبات اللازمة لتحقيق ذلك. 
8 –  على المقال توفير حاويات خاصة بالشركة للتخلص من القمامة والنفايات الناتجة من الموقع أثناء تنفيذ الأعمال ويمنع استخدام حاويات البلدية لهذا الغرض.
9 – على المقاول استخدام شركة متخصصة لتنظيف المبنى (والأعمال المنفذة) من الداخل والخارج عند إنهاء وإنجاز الأعمال ( وقبل الاستلام الابتدائي ).
10 – على المقاول متابعة المعاملات والاجراءات الرسمية وإنهاء جميع الموافقات الإدارية وإصدار شهادة إنجاز للمبنى ليكون المبنى جاهز (تسليم مفتاح) ضمن المدة المحددة لتنفيذ المشروع.
